/** @param {{ id?: string } | null} hit */
export function classifyUaHit(hit) {
  if (!hit?.id) return null;
  const id = hit.id;
  if (SCANNER_UA_IDS.has(id) || /\b(scan|exploit|vuln|security)\b/i.test(id)) return 'scanner';
  if (AUTOMATION_UA_IDS.has(id)) return 'automation';
  if (BOT_CLIENT_UA_IDS.has(id)) return 'bot_client';
  if (CRAWLER_UA_IDS.has(id) || /\b(bot|spider|crawler)\b/i.test(id)) return 'crawler';
  return 'suspicious';
}
