/**
 * Expanded WAF-style detection signatures for Slark middleware.
 */

/** @param {string} id @param {string} pattern @param {string} [flags] */
function rule(id, pattern, flags = 'i') {
  return { re: new RegExp(pattern, flags), id };
}

/** Build path probe regex at runtime. */
function rx(p, flags = 'i') {
  return new RegExp(p, flags);
}

function dedupeRules(list) {
  const seen = new Set();
  return list.filter((r) => {
    if (seen.has(r.id)) return false;
    seen.add(r.id);
    return true;
  });
}

/** @param {string} fragment */
function scannerPathRule(fragment) {
  const safe = fragment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const id = `path_${fragment.replace(/[^a-z0-9]+/gi, '_').replace(/^_|_$/g, '') || 'probe'}`;
  return { re: rx(`^/${safe}(?:/|$|\\?)`), id };
}

