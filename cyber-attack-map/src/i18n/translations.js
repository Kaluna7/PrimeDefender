/**
 * @param {Locale} locale
 * @param {string} key dot.path
 * @param {Record<string, string | number>} [vars]
 */
function lookup(dict, parts) {
  let v = dict;
  for (const p of parts) {
    v = v?.[p];
  }
  return v;
}

export function translate(_locale, key, vars) {
  const parts = key.split('.');
  const dict = translations.id;
  let v = lookup(dict, parts);
  let out = typeof v === 'string' ? v : key;
  if (vars) {
    for (const [k, val] of Object.entries(vars)) {
      out = out.replace(new RegExp('\\{' + k + '\\}', 'g'), String(val));
    }
  }
  return out;
}
